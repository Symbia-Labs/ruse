//! Turns a manifest into the files of a plugin crate.
//!
//! Everything here is generated except `src/dsp.rs`, which the agent owns. Regenerating after a manifest change
//! leaves `dsp.rs` alone.

use crate::manifest::{camel, snake, Manifest, Package, Param};

pub const GENERATED: &str = "// Generated by muse-mcp from manifest.json. Change the plugin through update_plugin, not this file.\n";

pub fn package_name(name: &str) -> String {
    format!("plugin-{}", name)
}

/// A Rust string literal for any text.
fn lit_str(s: &str) -> String {
    format!("{:?}", s)
}

/// A float literal that Rust reads as f32.
fn lit_f32(v: f64) -> String {
    format!("{:?}", v as f32)
}

fn base_expr(p: &Param) -> String {
    match p.kind.as_str() {
        "knob" => format!(
            "ParamInfo::knob({}, {}, {}, {}, {}, {})",
            lit_str(&p.id),
            lit_str(&p.name),
            lit_str(&p.unit),
            lit_f32(p.min),
            lit_f32(p.max),
            lit_f32(p.default)
        ),
        "meter" => format!(
            "ParamInfo::meter({}, {}, {}, {}, {})",
            lit_str(&p.id),
            lit_str(&p.name),
            lit_str(&p.unit),
            lit_f32(p.min),
            lit_f32(p.max)
        ),
        "choice" => {
            let names: Vec<String> = p.choices.iter().map(|c| lit_str(c)).collect();
            format!(
                "ParamInfo::choice({}, {}, &[{}], {})",
                lit_str(&p.id),
                lit_str(&p.name),
                names.join(", "),
                p.default as usize
            )
        }
        _ => format!(
            "ParamInfo::toggle({}, {}, {})",
            lit_str(&p.id),
            lit_str(&p.name),
            p.default >= 0.5
        ),
    }
}

pub fn declaration(m: &Manifest) -> String {
    let mut o = String::new();
    o.push_str(GENERATED);
    o.push_str("#![allow(dead_code, unused_imports)]\n\n");
    o.push_str("use muse_core::{Curve, ParamInfo, ParamSet};\n\n");
    o.push_str(&format!("pub const MAX_CHANNELS: usize = {};\n\n", m.max_channels));
    o.push_str(&format!("pub const PARAMS: [ParamInfo; {}] = [\n", m.params.len()));
    for p in &m.params {
        let mut base = base_expr(p);
        if p.scope == "per_channel" {
            base.push_str(".per_channel()");
        }
        o.push_str("    ParamInfo {\n");
        o.push_str(&format!("        description: {},\n", lit_str(&p.description)));
        o.push_str(&format!("        group: {},\n", lit_str(&p.group)));
        if p.curve == "log" {
            o.push_str("        curve: Curve::Log,\n");
        }
        o.push_str(&format!("        ..{}\n", base));
        o.push_str("    },\n");
    }
    o.push_str("];\n\n");

    o.push_str("/// The parameter values as the signal processing reads them.\n");
    o.push_str("pub struct Params<'a> {\n    set: &'a ParamSet,\n}\n\n");
    o.push_str("impl<'a> Params<'a> {\n");
    o.push_str("    pub fn new(set: &'a ParamSet) -> Self {\n        Params { set }\n    }\n\n");
    o.push_str("    /// All the parameters, for the block graph to read by position.\n    pub fn set(&self) -> &'a ParamSet {\n        self.set\n    }\n");
    for (i, p) in m.params.iter().enumerate() {
        let doc = p.description.lines().next().unwrap_or("").trim();
        o.push('\n');
        o.push_str(&format!("    /// {}: {}\n", p.name.replace('\n', " "), doc));
        let per_channel = p.scope == "per_channel";
        match (p.kind.as_str(), per_channel) {
            ("knob", false) => o.push_str(&format!(
                "    pub fn {}(&self) -> f32 {{\n        self.set.at({}).get()\n    }}\n",
                p.id, i
            )),
            ("knob", true) => o.push_str(&format!(
                "    pub fn {}(&self, channel: usize) -> f32 {{\n        self.set.at({}).get_ch(channel)\n    }}\n",
                p.id, i
            )),
            ("choice", false) => o.push_str(&format!(
                "    /// The index of the chosen name.\n    pub fn {}(&self) -> usize {{\n        self.set.at({}).get() as usize\n    }}\n",
                p.id, i
            )),
            ("choice", true) => o.push_str(&format!(
                "    /// The index of the chosen name.\n    pub fn {}(&self, channel: usize) -> usize {{\n        self.set.at({}).get_ch(channel) as usize\n    }}\n",
                p.id, i
            )),
            ("toggle", false) => o.push_str(&format!(
                "    pub fn {}(&self) -> bool {{\n        self.set.at({}).get() >= 0.5\n    }}\n",
                p.id, i
            )),
            ("toggle", true) => o.push_str(&format!(
                "    pub fn {}(&self, channel: usize) -> bool {{\n        self.set.at({}).get_ch(channel) >= 0.5\n    }}\n",
                p.id, i
            )),
            _ => o.push_str(&format!(
                "    /// Meters are written by the signal processing and read by everyone else.\n    pub fn set_{}(&self, value: f32) {{\n        self.set.at({}).set(value);\n    }}\n",
                p.id, i
            )),
        }
    }
    o.push_str("}\n");
    o
}

pub fn lib_rs(m: &Manifest) -> String {
    let ty = camel(&m.name);
    let mut o = String::new();
    o.push_str(GENERATED);
    o.push_str("#![forbid(unsafe_code)]\n\nmod declaration;\npub mod dsp;\n\n");
    o.push_str("pub use declaration::{Params, MAX_CHANNELS, PARAMS};\n");
    o.push_str("use muse_core::{BusInfo, Channels, Layout, ParamSet, Plugin, ProcessContext, Setup};\n\n");
    o.push_str(&format!(
        "const LAYOUT: Layout = Layout {{\n    inputs: &[BusInfo {{\n        name: \"Main\",\n        channels: Channels::Range {{ min: {}, max: {} }},\n    }}],\n    outputs: &[BusInfo {{\n        name: \"Main\",\n        channels: Channels::SameAsInput,\n    }}],\n}};\n\n",
        m.min_channels, m.max_channels
    ));
    o.push_str(&format!("/// {}\n", m.description.lines().next().unwrap_or("").trim()));
    o.push_str(&format!(
        "pub struct {ty} {{\n    params: ParamSet,\n    state: dsp::State,\n}}\n\n"
    ));
    o.push_str(&format!(
        "impl {ty} {{\n    pub fn new() -> Self {{\n        {ty} {{\n            params: ParamSet::with_channels(&PARAMS, MAX_CHANNELS),\n            state: dsp::State::new(),\n        }}\n    }}\n}}\n\n"
    ));
    o.push_str(&format!(
        "impl Default for {ty} {{\n    fn default() -> Self {{\n        Self::new()\n    }}\n}}\n\n"
    ));
    o.push_str(&format!(
        "impl Plugin for {ty} {{\n    fn layout(&self) -> Layout {{\n        LAYOUT\n    }}\n\n    fn params(&self) -> &ParamSet {{\n        &self.params\n    }}\n\n    fn prepare(&mut self, setup: &Setup) {{\n        self.state.prepare(setup);\n    }}\n\n    fn latency_samples(&self) -> u32 {{\n        self.state.latency_samples()\n    }}\n\n    fn tail_samples(&self) -> u32 {{\n        self.state.tail_samples()\n    }}\n\n    fn process(&mut self, channels: &mut [&mut [f32]], ctx: &ProcessContext) {{\n        self.state.process(&Params::new(&self.params), channels, ctx);\n    }}\n}}\n"
    ));
    o
}

pub fn cargo_toml(m: &Manifest) -> String {
    format!(
        "[package]\nname = \"{}\"\nversion = \"0.0.1\"\nedition = \"2021\"\nlicense = \"MIT\"\ndescription = {}\n\n[dependencies]\nmuse-core = {{ path = \"../../crates/core\" }}\nmuse-blocks = {{ path = \"../../crates/blocks\" }}\nmuse-host = {{ path = \"../../crates/host\" }}\n",
        package_name(&m.name),
        lit_str(m.description.lines().next().unwrap_or("").trim())
    )
}

pub fn render_bin(m: &Manifest) -> String {
    format!(
        "{}fn main() {{\n    muse_host::cli::render_main({}, plugin_{}::{}::new);\n}}\n",
        GENERATED,
        lit_str(&m.name),
        snake(&m.name),
        camel(&m.name)
    )
}

pub fn gates_test(m: &Manifest) -> String {
    format!(
        "{}#[global_allocator]\nstatic ALLOC: muse_host::alloc::CountingAlloc = muse_host::alloc::CountingAlloc::new();\n\n#[test]\nfn gates() {{\n    let results = muse_host::gates::run_all(plugin_{}::{}::new);\n    println!(\"{{}}\", muse_host::gates::report(&results));\n    assert!(muse_host::gates::all_passed(&results), \"one or more gates failed\");\n}}\n",
        GENERATED,
        snake(&m.name),
        camel(&m.name)
    )
}

/// The packaging crate sits beside the plugin so the workspace's `plugins/*` pattern picks it up.
pub fn clap_dir_name(name: &str) -> String {
    format!("{}-clap", name)
}

pub fn clap_package_name(name: &str) -> String {
    format!("plugin-{}-clap", name)
}

/// The file name Cargo gives the shared library the packaging crate builds, without a platform prefix.
pub fn clap_library_stem(name: &str) -> String {
    format!("{}_clap", snake(name))
}

pub fn clap_cargo_toml(m: &Manifest) -> String {
    format!(
        "[package]\nname = \"{}\"\nversion = \"0.0.1\"\nedition = \"2021\"\nlicense = \"MIT\"\n\n[lib]\nname = \"{}\"\ncrate-type = [\"cdylib\"]\n\n[dependencies]\nmuse-clap = {{ path = \"../../crates/clap\" }}\n{} = {{ path = \"../{}\" }}\n",
        clap_package_name(&m.name),
        clap_library_stem(&m.name),
        package_name(&m.name),
        m.name
    )
}

pub fn clap_lib_rs(m: &Manifest, p: &Package) -> String {
    let features: Vec<String> = p.features.iter().map(|f| lit_str(f)).collect();
    let mut o = String::new();
    o.push_str("// Generated by muse-mcp from manifest.json. Change the package settings through package_plugin, not this file.\n");
    o.push_str("muse_clap::export_clap! {\n");
    o.push_str(&format!("    plugin: plugin_{}::{},\n", snake(&m.name), camel(&m.name)));
    o.push_str(&format!("    id: {},\n", lit_str(&p.id)));
    o.push_str(&format!("    name: {},\n", lit_str(&m.title)));
    o.push_str(&format!("    vendor: {},\n", lit_str(&p.vendor)));
    o.push_str(&format!("    url: {},\n", lit_str(&p.url)));
    o.push_str(&format!("    version: {},\n", lit_str(&p.version)));
    o.push_str(&format!(
        "    description: {},\n",
        lit_str(m.description.lines().next().unwrap_or("").trim())
    ));
    o.push_str(&format!("    features: [{}],\n", features.join(", ")));
    o.push_str("}\n");
    o
}

/// The Audio Unit packaging crate, beside the plugin like the CLAP one.
pub fn au_dir_name(name: &str) -> String {
    format!("{}-au", name)
}

pub fn au_package_name(name: &str) -> String {
    format!("plugin-{}-au", name)
}

pub fn au_library_stem(name: &str) -> String {
    format!("{}_au", snake(name))
}

/// The function the component's Info.plist names as its factory.
pub fn au_factory_name(name: &str) -> String {
    format!("{}Factory", camel(name))
}

pub fn au_cargo_toml(m: &Manifest) -> String {
    format!(
        "[package]\nname = \"{}\"\nversion = \"0.0.1\"\nedition = \"2021\"\nlicense = \"MIT\"\n\n[lib]\nname = \"{}\"\ncrate-type = [\"cdylib\"]\n\n[dependencies]\nmuse-au = {{ path = \"../../crates/au\" }}\n{} = {{ path = \"../{}\" }}\n",
        au_package_name(&m.name),
        au_library_stem(&m.name),
        package_name(&m.name),
        m.name
    )
}

pub fn au_lib_rs(m: &Manifest) -> String {
    let mut o = String::new();
    o.push_str("// Generated by muse-mcp from manifest.json. Change the package settings through package_plugin, not this file.\n");
    o.push_str("// Audio Units exist on macOS only, so the crate is empty elsewhere.\n");
    o.push_str("#![cfg(target_os = \"macos\")]\n\n");
    o.push_str("muse_au::export_au! {\n");
    o.push_str(&format!("    plugin: plugin_{}::{},\n", snake(&m.name), camel(&m.name)));
    o.push_str(&format!("    factory: {},\n", au_factory_name(&m.name)));
    o.push_str("}\n");
    o
}

/// The starting point for `src/dsp.rs`. It passes audio through unchanged.
pub fn dsp_template() -> String {
    include_str!("dsp_template.txt").to_string()
}

/// The first line of a dsp.rs that was generated from a graph. It tells a later change from agent-written code.
pub const GRAPH_DSP_MARKER: &str = "// Generated by muse-mcp from the graph in manifest.json.";

/// The signal processing of a plugin whose signal path is a graph of blocks.
pub fn graph_dsp(m: &Manifest, graph: &crate::json::Json) -> String {
    let text = graph.compact();
    // A raw string with more hashes than any run of them in the text, so nothing inside can end it early.
    let mut longest = 0;
    let mut run = 0;
    for c in text.chars() {
        if c == '#' {
            run += 1;
            longest = longest.max(run);
        } else {
            run = 0;
        }
    }
    let hashes = "#".repeat(longest + 1);
    include_str!("graph_dsp_template.txt")
        .replace("@MARKER@", GRAPH_DSP_MARKER)
        .replace("@TITLE@", &m.title)
        .replace("@GRAPH@", &format!("r{h}\"{text}\"{h}", h = hashes, text = text))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{json, manifest};

    fn sample() -> Manifest {
        manifest::parse(
            &json::parse(
                r#"{"name":"warm-saturator","description":"Adds warmth.","channels_max":8,"parameters":[
                {"id":"drive","name":"Drive","description":"How hard.","unit":"dB","min":0,"max":24,"default":6,"group":"Main"},
                {"id":"tone","name":"Tone","description":"Brightness.","unit":"Hz","min":200,"max":8000,"default":2000,"curve":"log","scope":"per_channel"},
                {"id":"mode","name":"Mode","description":"Curve.","kind":"choice","choices":["Soft","Hard"]},
                {"id":"bypass","name":"Bypass","description":"Pass through.","kind":"toggle"},
                {"id":"level","name":"Level","description":"Output level.","kind":"meter","unit":"dB","min":-96,"max":6}]}"#,
            )
            .unwrap(),
        )
        .unwrap()
    }

    #[test]
    fn a_graph_plugin_gets_a_generated_dsp_that_embeds_the_graph() {
        let m = sample();
        let g = json::parse(r#"{"block":"gain","args":{"gain_db":"drive"}}"#).unwrap();
        let src = graph_dsp(&m, &g);
        assert!(src.starts_with(GRAPH_DSP_MARKER), "the marker is how a later change tells it from written code");
        assert!(src.contains("const GRAPH: &str = r#\"{\"block\":\"gain\",\"args\":{\"gain_db\":\"drive\"}}\"#;"), "{}", src);
        assert!(src.contains("self.graph.process(p.set(), channels, ctx)"));
        assert!(src.contains("Warm Saturator"), "the title is named in the header");
        assert!(!src.contains('@'), "every placeholder was filled");
    }

    #[test]
    fn a_hash_inside_the_graph_cannot_end_the_raw_string_early() {
        let m = sample();
        let g = json::parse("{\"block\":\"gain\",\"args\":{\"note\":\"a\\\"#b\"}}").unwrap();
        let src = graph_dsp(&m, &g);
        assert!(src.contains("r##\""), "two hashes, one more than the longest run in the text: {}", src);
    }

    #[test]
    fn the_declaration_gives_the_graph_the_whole_parameter_set() {
        assert!(declaration(&sample()).contains("pub fn set(&self) -> &'a ParamSet"));
        assert!(cargo_toml(&sample()).contains("muse-blocks"));
    }

    #[test]
    fn the_declaration_holds_every_parameter_and_accessor() {
        let d = declaration(&sample());
        assert!(d.contains("pub const PARAMS: [ParamInfo; 5]"));
        assert!(d.contains("ParamInfo::knob(\"drive\", \"Drive\", \"dB\", 0.0, 24.0, 6.0)"));
        assert!(d.contains("curve: Curve::Log"));
        assert!(d.contains(".per_channel()"));
        assert!(d.contains("pub fn drive(&self) -> f32"));
        assert!(d.contains("pub fn tone(&self, channel: usize) -> f32"));
        assert!(d.contains("pub fn mode(&self) -> usize"));
        assert!(d.contains("pub fn bypass(&self) -> bool"));
        assert!(d.contains("pub fn set_level(&self, value: f32)"));
        assert!(d.contains("pub const MAX_CHANNELS: usize = 8;"));
    }

    #[test]
    fn the_other_files_name_the_plugin() {
        let m = sample();
        assert!(lib_rs(&m).contains("pub struct WarmSaturator"));
        assert!(lib_rs(&m).contains("Channels::Range { min: 1, max: 8 }"));
        assert!(cargo_toml(&m).contains("name = \"plugin-warm-saturator\""));
        assert!(render_bin(&m).contains("plugin_warm_saturator::WarmSaturator::new"));
        assert!(gates_test(&m).contains("plugin_warm_saturator::WarmSaturator::new"));
        assert!(dsp_template().contains("pub fn process"));
    }

    #[test]
    fn the_packaging_crate_names_the_plugin_and_its_settings() {
        let m = sample();
        let mut p = Package {
            vendor: "Symbia Labs".to_string(),
            url: "https://example.com".to_string(),
            features: vec!["audio-effect".to_string(), "distortion".to_string()],
            ..Package::default()
        };
        p.complete(&m.name).unwrap();
        let lib = clap_lib_rs(&m, &p);
        assert!(lib.contains("plugin: plugin_warm_saturator::WarmSaturator,"));
        assert!(lib.contains("id: \"symbia-labs.warm-saturator\","));
        assert!(lib.contains("name: \"Warm Saturator\","));
        assert!(lib.contains("features: [\"audio-effect\", \"distortion\"],"));
        let toml = clap_cargo_toml(&m);
        assert!(toml.contains("name = \"plugin-warm-saturator-clap\""));
        assert!(toml.contains("crate-type = [\"cdylib\"]"));
        assert!(toml.contains("plugin-warm-saturator = { path = \"../warm-saturator\" }"));
        assert_eq!(clap_dir_name("warm-saturator"), "warm-saturator-clap");
        assert_eq!(clap_library_stem("warm-saturator"), "warm_saturator_clap");
    }

    #[test]
    fn the_audio_unit_crate_names_the_plugin_and_its_factory() {
        let m = sample();
        let lib = au_lib_rs(&m);
        assert!(lib.contains("#![cfg(target_os = \"macos\")]"));
        assert!(lib.contains("plugin: plugin_warm_saturator::WarmSaturator,"));
        assert!(lib.contains("factory: WarmSaturatorFactory,"));
        let toml = au_cargo_toml(&m);
        assert!(toml.contains("name = \"plugin-warm-saturator-au\""));
        assert!(toml.contains("name = \"warm_saturator_au\""));
        assert!(toml.contains("muse-au = { path = \"../../crates/au\" }"));
        assert!(toml.contains("plugin-warm-saturator = { path = \"../warm-saturator\" }"));
        assert_eq!(au_dir_name("warm-saturator"), "warm-saturator-au");
        assert_eq!(au_library_stem("warm-saturator"), "warm_saturator_au");
        assert_eq!(au_factory_name("gain"), "GainFactory");
    }

    #[test]
    fn text_with_quotes_and_newlines_is_escaped() {
        let mut m = sample();
        m.params[0].description = "Says \"hi\"\nand more".to_string();
        let d = declaration(&m);
        assert!(d.contains("description: \"Says \\\"hi\\\"\\nand more\""));
    }
}
